#!/usr/bin/env python3
"""Generate the case files whose question or option lists are too long to hand-write.

Run from the jev_eval directory:  python3 scripts/gen_large_cases.py
"""

import json
import os

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "cases")

# --------------------------------------------------------------------------
# C5: the same three products classified against 3, 20 and 100 options
# --------------------------------------------------------------------------

TARGETS = {
    "water_bottles": "Reusable bottles for drinking water",
    "running_shoes": "Shoes designed for road or trail running",
    "desk_lamps": "Lamps intended for a desk or work surface",
}

FILLER = [
    "bike_lights", "helmets", "yoga_mats", "resistance_bands", "tents",
    "sleeping_bags", "hydration_packs", "travel_mugs", "tumblers", "pots_and_pans",
    "bakeware", "sippy_cups", "bottle_warmers", "bibs", "office_chairs",
    "standing_desks", "monitor_arms", "keyboards", "mice", "webcams",
    "headphones", "earbuds", "speakers", "soundbars", "televisions",
    "streaming_sticks", "game_consoles", "controllers", "board_games", "puzzles",
    "hiking_boots", "sandals", "dress_shoes", "socks", "rain_jackets",
    "down_jackets", "base_layers", "gloves", "hats", "sunglasses",
    "backpacks", "duffel_bags", "suitcases", "packing_cubes", "travel_adapters",
    "power_banks", "charging_cables", "wall_chargers", "surge_protectors", "extension_cords",
    "floor_lamps", "ceiling_lights", "light_bulbs", "candles", "picture_frames",
    "wall_shelves", "storage_bins", "laundry_baskets", "ironing_boards", "vacuum_cleaners",
    "air_purifiers", "humidifiers", "space_heaters", "fans", "thermostats",
    "coffee_makers", "espresso_machines", "kettles", "blenders", "food_processors",
    "toasters", "air_fryers", "slow_cookers", "knife_sets", "cutting_boards",
    "dinnerware", "glassware", "cutlery", "food_containers", "lunch_boxes",
    "dog_beds", "dog_leashes", "cat_trees", "pet_bowls", "pet_carriers",
    "garden_hoses", "pruning_shears", "plant_pots", "potting_soil", "bird_feeders",
    "hand_tools", "power_drills", "tool_boxes", "work_gloves", "safety_glasses",
    "notebooks", "pens", "desk_organizers",
]

C5_STATES = [
    ("bike_bottle", "32oz plastic bottle with a flip straw lid. Fits most bike cages.", "water_bottles"),
    ("road_runner", "Lightweight road running shoe with an 8mm drop and a breathable mesh upper.", "running_shoes"),
    ("led_lamp", "LED desk lamp with adjustable colour temperature and a USB-C charging port.", "desk_lamps"),
]


def options(n):
    """n options, always including the three correct answers."""
    criteria = dict(TARGETS)
    for name in FILLER[: n - len(TARGETS)]:
        criteria[name] = name.replace("_", " ").capitalize()
    return criteria


def build_c5():
    variants = []
    for n in (3, 20, 100):
        variants.append({
            "id": "options_%d" % n,
            "questions": {
                "category": {
                    "type": "choice",
                    "instructions": "Which category does this product belong to?",
                    "criteria": options(n),
                }
            },
        })
    states = []
    for sid, text, correct in C5_STATES:
        states.append({"id": sid, "state": text,
                       "expect": {"category": {"equals": correct}}})
    return {
        "id": "c5_option_count",
        "group": "choice",
        "title": "C5 - does a Choice hold up as the option list grows",
        "doc_ref": "docs.typesafe.ai/primitives/choice - 'A Choice question accepts up to 255 options'",
        "note": ("The docs recommend giving the full list rather than a shortlist, and say extra "
                 "options cost only a few tokens each. They do not publish what happens to accuracy "
                 "or confidence at 100 options. The correct answer is present in every variant, so "
                 "any drop is the option list itself and not the question. Generated by "
                 "scripts/gen_large_cases.py."),
        "variants": variants,
        "states": states,
        "relations": [
            {"type": "variant_profile", "question": "category"},
            {"type": "variant_agreement", "baseline": "options_3"},
            {"type": "report", "question": "category"},
        ],
    }


# --------------------------------------------------------------------------
# M3: response time against the number of questions in one request
# --------------------------------------------------------------------------

M3_STATE = ("Shoes arrived two weeks late and in the wrong size. Also I see two charges "
            "of $120 on my card. What are you going to do about this?")

PROBE_QUESTIONS = [
    ("is_urgent", "Does this message convey urgency?"),
    ("wants_refund", "Does the customer request a refund?"),
    ("is_angry", "Is the customer angry?"),
    ("mentions_payment", "Does the message mention a payment or charge?"),
    ("mentions_delivery", "Does the message mention delivery or shipping?"),
    ("mentions_sizing", "Does the message mention a size or fit problem?"),
    ("asks_question", "Does the message ask a direct question?"),
    ("is_repeat_contact", "Has the customer contacted support about this before?"),
    ("wants_human", "Is the customer asking for a human agent?"),
    ("threatens_churn", "Does the customer threaten to stop being a customer?"),
    ("mentions_timeline", "Does the message state how long the problem has lasted?"),
    ("contains_pii", "Does the message contain personal data?"),
    ("mentions_order_id", "Does the message reference a specific order?"),
    ("is_profane", "Does the message contain profanity?"),
    ("requests_callback", "Does the customer ask to be called back?"),
    ("mentions_competitor", "Does the message mention a competitor?"),
    ("is_legal_threat", "Does the message threaten legal action?"),
    ("mentions_warranty", "Does the message mention a warranty or guarantee?"),
    ("is_duplicate_report", "Does the message describe more than one separate problem?"),
    ("wants_exchange", "Does the customer ask to swap an item for a different one?"),
    ("mentions_discount", "Does the message ask for a discount or credit?"),
    ("is_positive", "Does the message express satisfaction?"),
    ("mentions_app", "Does the message mention a mobile app?"),
    ("mentions_website", "Does the message mention the website?"),
    ("mentions_email", "Does the message mention an email that was sent or received?"),
    ("is_followup", "Does the message refer to an earlier conversation?"),
    ("needs_engineer", "Would answering this require an engineer?"),
    ("is_billing_dispute", "Does the customer dispute a charge?"),
    ("mentions_address", "Does the message mention a delivery address?"),
    ("is_time_sensitive", "Does the message state a deadline?"),
]


def build_m3():
    variants = []
    for n in (1, 3, 10, 30):
        variants.append({
            "id": "q%02d" % n,
            "questions": {
                qid: {"type": "noul", "instructions": text}
                for qid, text in PROBE_QUESTIONS[:n]
            },
        })
    return {
        "id": "m3_latency_scaling",
        "group": "meta",
        "title": "M3 - response time against the number of questions",
        "doc_ref": "docs.typesafe.ai/primitives - 'Adding questions barely changes the response time'",
        "note": ("One state asked with 1, 3, 10 and 30 questions, ten times each, run strictly "
                 "serially so wall-clock time means something. The docs claim questions are "
                 "evaluated in parallel and that adding them barely moves latency. Generated by "
                 "scripts/gen_large_cases.py."),
        "repeat": 10,
        "sequential": True,
        "variants": variants,
        "states": [{"id": "three_way", "state": M3_STATE}],
        "relations": [{"type": "latency_profile"}],
    }


def build_m2():
    """One call with 13 questions against 13 calls with one question each."""
    questions = {
        qid: {"type": "noul", "instructions": text}
        for qid, text in PROBE_QUESTIONS[:13]
    }
    return {
        "id": "m2_batching_gain",
        "group": "meta",
        "title": "M2 - reproduce the published cost and speed advantage of batching",
        "doc_ref": "docs.typesafe.ai/primitives - 'batching 13 questions into one call is 11.5x cheaper and 9.6x faster'",
        "note": ("The docs put a precise number on batching: thirteen questions in one request "
                 "against thirteen separate requests, 11.5x cheaper and 9.6x faster, with no "
                 "change in the answers. Both arms run serially here so the speed ratio is a fair "
                 "wall-clock comparison. The answer-identity half doubles as the strongest test of "
                 "the independence claim: if a question's answer shifts when twelve unrelated "
                 "questions sit beside it, they are not evaluated in isolation. Generated by "
                 "scripts/gen_large_cases.py."),
        "sequential": True,
        "variants": [
            {"id": "batched", "questions": questions},
            {"id": "split", "split": True, "questions": questions,
             "note": "Same thirteen questions, one request each."},
        ],
        "states": [
            {"id": "three_way", "state": M3_STATE},
            {"id": "simple", "state": "My running shoes arrived in the wrong size. Can I swap them for a size 10?"},
        ],
        "relations": [
            {"type": "batching_gain", "batched": "batched", "split": "split", "max_delta": 0.05},
            {"type": "answers_match", "question": "is_urgent",
             "variants": ["batched", "split"], "field": "value", "tol": 0.05},
        ],
    }


def main():
    for subdir, case in (("choice", build_c5()), ("meta", build_m3()), ("meta", build_m2())):
        path = os.path.join(OUT, subdir, case["id"] + ".json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(case, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
        print("wrote %s (%d variants, %d states)"
              % (os.path.relpath(path, os.path.dirname(OUT)), len(case["variants"]),
                 len(case["states"])))


if __name__ == "__main__":
    main()
